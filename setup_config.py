#!/usr/bin/env python3
"""Write Telegram credentials into config.json -- WITHOUT hardcoding them.

WHY THIS FILE WAS REWRITTEN
---------------------------
This script used to contain the real ``api_hash`` and phone number as literals::

    app.save_tg_config("35578684", "0c28170bc8f7...", "+91928...", "@tgwebcloud1")

That was committed in 6 commits (``45af352``, ``ddd99f9``, ``f117a5d``,
``198962f``, ``4efa7b4``, ``b503b26``) and is permanently recoverable from git
history even after this edit.

The config file it writes already protects ``api_hash`` with Windows DPAPI
(``app._protect_api_hash`` / ``api_hash_protected``). DPAPI encryption of the
output was pointless: the plaintext key sat in the *input*, in source. A secret
that is hardcoded anywhere in the tree is not a secret, it is a published value
with extra steps.

RULE (see AGENTS.md #2): credentials come from the environment. Never from a
literal, never from a committed file.

USAGE
-----
    $env:TDUBBER_API_ID    = "1234567"
    $env:TDUBBER_API_HASH  = "<your api_hash>"
    $env:TDUBBER_PHONE     = "+91XXXXXXXXXX"
    $env:TDUBBER_CHANNEL   = "@yourchannel"      # optional, defaults to this
    python setup_config.py

Nothing is printed back. The channel name is echoed; the hash never is.
"""

from __future__ import annotations

import os
import sys

APP_DIR = os.path.dirname(os.path.abspath(__file__))
if APP_DIR not in sys.path:
    sys.path.insert(0, APP_DIR)

# Fallback channel only. A channel handle is a public identifier, so it carries
# no secret value -- unlike the api_hash and phone that used to sit next to it.
DEFAULT_CHANNEL = "@tgwebcloud1"

_REQUIRED = ("TDUBBER_API_ID", "TDUBBER_API_HASH", "TDUBBER_PHONE")


def read_env() -> tuple[str, str, str, str]:
    """Pull credentials from the environment.

    Returns:
        A ``(api_id, api_hash, phone, channel)`` tuple.

    Raises:
        SystemExit: if any of the three required variables is missing or empty.
            The message names the variables that are absent so the operator does
            not have to guess which one they forgot.
    """
    missing = [name for name in _REQUIRED if not os.environ.get(name, "").strip()]
    if missing:
        raise SystemExit(
            "Cannot write config.json -- these environment variables are unset:\n"
            + "".join(f"  - {name}\n" for name in missing)
            + "\nSet them in your shell, then re-run. Do NOT edit this file to add\n"
            "them back: a credential written into source is a published credential."
        )

    channel = os.environ.get("TDUBBER_CHANNEL", "").strip() or DEFAULT_CHANNEL
    return (
        os.environ["TDUBBER_API_ID"].strip(),
        os.environ["TDUBBER_API_HASH"].strip(),
        os.environ["TDUBBER_PHONE"].strip(),
        channel,
    )


def main() -> int:
    """Write the config, reporting only non-secret fields.

    Returns:
        0 on success, 1 if anything went wrong. The exit code is the contract
        for shell callers, so this script stays usable from PowerShell and the
        Kaggle bootstrap without parsing its output.
    """
    api_id, api_hash, phone, channel = read_env()

    try:
        import app
    except Exception as exc:  # noqa: BLE001 -- report, do not traceback
        print(f"Could not import app: {exc}", file=sys.stderr)
        return 1

    try:
        result = app.save_tg_config(api_id, api_hash, phone, channel)
    except Exception as exc:  # noqa: BLE001 -- report, do not traceback
        print(f"save_tg_config failed: {exc}", file=sys.stderr)
        return 1

    print(f"Config setup result: {result}")
    # The api_hash is deliberately absent from this line. Neither is it length.
    print(f"Stored api_id={api_id}, phone={phone}, channel={channel}")
    print("api_hash was written DPAPI-encrypted and is not echoed here.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
